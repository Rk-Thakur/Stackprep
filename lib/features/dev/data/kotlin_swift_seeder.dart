class _SeedTrack {
  const _SeedTrack({
    required this.id,
    required this.name,
    required this.description,
    required this.category,
    required this.color,
    required this.order,
    required this.modules,
    required this.flipcards,
  });

  final String id;
  final String name;
  final String description;
  final String category;
  final int color;
  final int order;
  final List<_SeedModule> modules;
  final List<_SeedFlipcard> flipcards;
}

class _SeedModule {
  const _SeedModule({
    required this.id,
    required this.title,
    required this.description,
    required this.learningObjectives,
    required this.content,
    this.level = 'BEGINNER',
    this.questions = const [],
  });

  final String id;
  final String title;
  final String description;
  final List<String> learningObjectives;
  final String level;

  /// List of content block maps: {type, text} or {type, language, code}.
  final List<Map<String, dynamic>> content;
  final List<_SeedQuestion> questions;
}

class _SeedQuestion {
  _SeedQuestion({
    required this.id,
    required this.question,
    required this.options,
    required this.correctIndex,
    required this.level,
    this.codeHeader,
    this.codeLanguage,
    this.codeLines = const [],
  });

  final String id;
  final String question;
  final List<String> options;
  final int correctIndex;
  final String level;
  final String? codeHeader;
  final String? codeLanguage;
  final List<String> codeLines;

  Map<String, dynamic> toFirestore() {
    return {
      'question': question,
      'options': options,
      'correctIndex': correctIndex,
      'level': level,
      if (codeHeader != null) 'codeHeader': codeHeader,
      if (codeLanguage != null) 'codeLanguage': codeLanguage,
      if (codeLines.isNotEmpty) 'codeLines': codeLines,
    };
  }
}

class _SeedFlipcard {
  _SeedFlipcard({
    required this.id,
    required this.term,
    required this.definition,
    this.codeHeader,
    this.codeLanguage,
    this.codeLines = const [],
  });

  final String id;
  final String term;
  final String definition;
  final String? codeHeader;
  final String? codeLanguage;
  final List<String> codeLines;

  Map<String, dynamic> toFirestore() {
    return {
      'term': term,
      'definition': definition,
      if (codeHeader != null) 'codeHeader': codeHeader,
      if (codeLanguage != null) 'codeLanguage': codeLanguage,
      if (codeLines.isNotEmpty) 'codeLines': codeLines,
    };
  }
}

